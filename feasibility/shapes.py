"""Payment-vector building blocks: per-position floors, shape labels, static legality.

``compute_floors`` turns base minimum, token-pay limit and tiers into a floor per
position. ``is_statically_valid`` is the money-independent legality filter,
``label_shape`` names the shape by rule, ``even_vector`` is the even split; the engine's
exact search (``search.py``) uses all four. The vectors themselves are generated by
``search.Search`` (``pinned`` / ``boxed``), not here; the take-home enumeration that
used to live here was removed in Phase 61. No ledger or fee logic here: simulation is
``simulate.py``, scoring ``scoring.py``.
"""

from __future__ import annotations

from dataclasses import dataclass

from feasibility.models import CreditorRules


@dataclass(frozen=True)
class Candidate:
    """One payment vector of length ``k`` with its rule-based shape label."""

    k: int
    payments: tuple[int, ...]
    label: str  # "even" | "staircase" | "balloon"


def compute_floors(rules: CreditorRules, k_max: int) -> list[int]:
    """1-indexed floors[1..k_max]. floors[0] unused."""
    floors = [0] * (k_max + 1)
    for i in range(1, k_max + 1):
        tier = 0
        for frm, m in rules.min_payment_tiers:
            if frm <= i:
                tier = max(tier, m)
        token_bump = rules.min_payment_cents + 1 if i > rules.max_token_pays else 0
        floors[i] = max(rules.min_payment_cents, tier, token_bump)
    return floors


def label_shape(
    payments: tuple[int, ...],
    rules: CreditorRules,
) -> str:
    """Label by rule, not by generating family (case 3 needs balloon for dual generators)."""
    if rules.even_pays:
        return "even"
    k = len(payments)
    if rules.is_ballooning_allowed and k >= 2 and payments[-1] > payments[-2]:
        return "balloon"
    return "staircase"


def even_vector(S: int, k: int) -> tuple[int, ...]:
    """As-equal-as-possible split, remainder cents on the latest payments."""
    q, r = divmod(S, k)
    return tuple([q] * (k - r) + [q + 1] * r)


def is_statically_valid(
    k: int,
    payments: tuple[int, ...],
    S: int,
    k_max: int,
    floors: list[int],
    rules: CreditorRules,
    label: str | None = None,
) -> bool:
    """Money-independent legality checks (also the Part 2 candidate filter)."""
    if not (1 <= k <= k_max) or len(payments) != k:
        return False
    if sum(payments) != S:
        return False
    for i in range(k - 1):
        if payments[i] > payments[i + 1]:
            return False
    for i in range(1, k + 1):
        if payments[i - 1] < floors[i]:
            return False
    token_count = sum(1 for p in payments if p == rules.min_payment_cents)
    if token_count > rules.max_token_pays:
        return False

    if label is None:
        label = label_shape(payments, rules)

    if label == "even":
        return payments == even_vector(S, k)
    if label == "staircase":
        return len(set(payments)) <= rules.max_segments
    # balloon: exempt from max_segments
    return True
